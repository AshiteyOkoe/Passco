function clientIp(req: AuthRequest): string {
  const fwd = req.headers['x-forwarded-for'];
  if (typeof fwd === 'string' && fwd) return fwd.split(',')[0].trim();
  return req.ip || '';
}

const VERIFY_CHARS = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

function randomVerifyCode(): string {
  let out = 'PASSCO-VRF-';
  const bytes = crypto.randomBytes(8);
  for (let i = 0; i < 8; i++) out += VERIFY_CHARS[bytes[i] % VERIFY_CHARS.length];
  return out;
}

async function generateUniqueReportNumber(year: string): Promise<string> {
  const prefix = `PASSCO-RPT-${year.replace(/\D/g, '').slice(0, 4) || String(new Date().getFullYear())}-`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const candidate = `${prefix}${String(Math.floor(100000 + Math.random() * 900000))}`;
    const { data } = await supabase.from('report_cards').select('id').eq('report_number', candidate).maybeSingle();
    if (!data) return candidate;
  }
  return `${prefix}${Date.now().toString().slice(-6)}`;
}

async function generateUniqueVerificationCode(): Promise<string> {
  for (let attempt = 0; attempt < 5; attempt++) {
    const candidate = randomVerifyCode();
    const { data } = await supabase.from('report_cards').select('id').eq('verification_code', candidate).maybeSingle();
    if (!data) return candidate;
  }
  return randomVerifyCode();
}

function serialize(row: Record<string, unknown>) {
  return {
    id: row.id,
    userId: row.user_id,
    reportNumber: row.report_number,
    verificationCode: row.verification_code,
    academicYear: row.academic_year,
    term: row.term,
    periodLabel: row.period_label,
    periodStart: row.period_start,
    periodEnd: row.period_end,
    overallScore: Number(row.overall_score || 0),
    overallGrade: row.overall_grade,
    overallRemark: row.overall_remark,
    status: row.status,
    dataSnapshot: row.data_snapshot,
    profilePhotoSnapshotUrl: row.profile_photo_snapshot_url || '',
    generatedAt: row.generated_at,
    generatedBy: row.generated_by,
  };
}

export interface GenerateReportRecordInput {
  targetUserId: string;
  actorUserId?: string;
  body: Record<string, unknown>;
  ip?: string;
}

export async function generateReportRecord(input: GenerateReportRecordInput): Promise<ReturnType<typeof serialize>> {
  const { targetUserId, actorUserId, body: b, ip } = input;

  const academicYear = String(b.academicYear || String(new Date().getFullYear()));
  const term = String(b.term || 'Full Year');

  const { data: targetUser } = await supabase.from('users').select('name').eq('id', targetUserId).maybeSingle();
  if (!targetUser) throw new Error('Student not found');

  const reportNumber = await generateUniqueReportNumber(academicYear);
  const verificationCode = await generateUniqueVerificationCode();

  const overallScore = Math.max(0, Math.min(100, Number(b.overallScore ?? 0)));
  const overallGrade = String(b.overallGrade || 'F');
  const overallRemark = String(b.overallRemark || '');

  await supabase
    .from('report_cards')
    .update({ status: 'superseded' })
    .eq('user_id', targetUserId)
    .eq('academic_year', academicYear)
    .eq('term', term)
    .eq('status', 'current');

  const { data: record, error } = await supabase
    .from('report_cards')
    .insert({
      user_id: targetUserId,
      report_number: reportNumber,
      verification_code: verificationCode,
      academic_year: academicYear,
      term,
      period_label: String(b.periodLabel || ''),
      period_start: b.periodStart || null,
      period_end: b.periodEnd || null,
      overall_score: overallScore,
      overall_grade: overallGrade,
      overall_remark: overallRemark,
      data_snapshot: b.dataSnapshot || {},
      profile_photo_snapshot_url: String(b.profilePhotoSnapshotUrl || ''),
      generated_by: actorUserId,
    })
    .select()
    .single();

  if (error) throw error;

  await logAuditEvent({
    userId: actorUserId,
    action: 'report_generated',
    entityType: 'report_card',
    entityId: record.id,
    ipAddress: ip,
    details: { userId: targetUserId, academicYear, term, overallScore, reportNumber },
  });

  return serialize(record);
}

async function createReport(req: AuthRequest, res: Response, adminUserId?: string): Promise<void> {
  const targetUserId = adminUserId || req.user?.id;
  if (!targetUserId) {
    res.status(401).json({ message: 'Unauthorized' });
    return;
  }

  try {
    const record = await generateReportRecord({
      targetUserId,
      actorUserId: req.user?.id,
      body: (req.body || {}) as Record<string, unknown>,
      ip: clientIp(req),
    });
    res.status(201).json({ report: record });
  } catch (error) {
    console.error('Create report card error:', error);
    res.status(500).json({ message: 'Your report could not be generated. Please try again.' });
  }
}

export async function createReportCard(req: AuthRequest, res: Response): Promise<void> {
  await createReport(req, res);
}

export async function createReportCardForUser(req: AuthRequest, res: Response): Promise<void> {
  const userId = String((req.body as Record<string, unknown>)?.userId || '');
  if (!userId) {
    res.status(400).json({ message: 'Student is required' });
    return;
  }
  await createReport(req, res, userId);
}

