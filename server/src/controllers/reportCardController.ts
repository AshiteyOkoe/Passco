export async function getReportCard(req: AuthRequest, res: Response): Promise<void> {
  try {
    const id = String(req.params.id || '');
    const { data } = await supabase.from('report_cards').select('*').eq('id', id).maybeSingle();
    if (!data) {
      res.status(404).json({ message: 'Report not found' });
      return;
    }
    if (data.user_id !== req.user?.id && req.user?.role !== 'admin') {
      res.status(403).json({ message: 'You do not have access to this report' });
      return;
    }
    res.json({ report: serialize(data) });
  } catch {
    res.status(500).json({ message: 'Failed to load report' });
  }
}

export async function deleteReportCard(req: AuthRequest, res: Response): Promise<void> {
  try {
    const id = String(req.params.id || '');
    const { data } = await supabase.from('report_cards').select('id, user_id').eq('id', id).maybeSingle();
    if (!data) {
      res.status(404).json({ message: 'Report not found' });
      return;
    }
    if (data.user_id !== req.user?.id && req.user?.role !== 'admin') {
      res.status(403).json({ message: 'You do not have access to this report' });
      return;
    }

    const { error } = await supabase.from('report_cards').update({ status: 'void' }).eq('id', id);
    if (error) throw error;

    await logAuditEvent({
      userId: req.user?.id,
      action: 'report_deleted',
      entityType: 'report_card',
      entityId: id,
      ipAddress: clientIp(req),
    });

    res.json({ message: 'Report deleted' });
  } catch {
    res.status(500).json({ message: 'Failed to delete report' });
  }
}

export async function verifyReport(req: AuthRequest, res: Response): Promise<void> {
  try {
    const code = String(req.params.code || '');
    const { data } = await supabase
      .from('report_cards')
      .select('*, users(name)')
      .eq('verification_code', code)
      .neq('status', 'void')
      .maybeSingle();

    if (!data) {
      res.json({ found: false });
      return;
    }

    const fullName: string = (data.users as { name?: string } | null)?.name || '';
    const parts = fullName.trim().split(/\s+/);
    const masked =
      parts.length >= 2
        ? `${parts[0].charAt(0)}. ${parts.slice(1).join(' ')}`
        : parts[0]?.charAt(0).toUpperCase() || 'PASSCO Student';

    res.json({
      found: true,
      reportNumber: data.report_number,
      academicYear: data.academic_year,
      term: data.term,
      overallGrade: data.overall_grade,
      overallScore: Number(data.overall_score || 0),
      generatedAt: data.generated_at,
      studentNameMasked: masked,
    });
  } catch {
    res.status(500).json({ found: false });
  }
}

export async function getReportSettings(req: AuthRequest, res: Response): Promise<void> {
  try {
    const { data } = await supabase.from('platform_settings').select('value').eq('key', 'report').maybeSingle();
    res.json({ settings: (data?.value as ReportSettings) || DEFAULT_SETTINGS });
  } catch {
    res.json({ settings: DEFAULT_SETTINGS });
  }
}

export async function updateReportSettings(req: AuthRequest, res: Response): Promise<void> {
  try {
    const current = await getSettings();
    const incoming = (req.body || {}) as Partial<ReportSettings>;

    const gradeIn = incoming.gradeConfig;
    const gradeConfig = Array.isArray(gradeIn)
      ? gradeIn
          .filter((g) => g && typeof g.grade === 'string')
          .map((g) => ({
            grade: String(g.grade).toUpperCase(),
            min: Math.max(0, Math.min(100, Number(g.min || 0))),
            max: Math.max(0, Math.min(100, Number(g.max ?? 100))),
            remark: String(g.remark || ''),
          }))
          .sort((a, b) => b.min - a.min)
      : current.gradeConfig;

    const thresholds = incoming.thresholds && typeof incoming.thresholds === 'object'
      ? {
          pass: Math.max(0, Math.min(100, Number(incoming.thresholds.pass ?? current.thresholds.pass))),
          improve: Math.max(0, Math.min(100, Number(incoming.thresholds.improve ?? current.thresholds.improve))),
          strength: Math.max(0, Math.min(100, Number(incoming.thresholds.strength ?? current.thresholds.strength))),
        }
      : current.thresholds;

    const branding = incoming.branding && typeof incoming.branding === 'object'
      ? {
          reportTitle: String(incoming.branding.reportTitle ?? current.branding.reportTitle),
          subtitle: String(incoming.branding.subtitle ?? current.branding.subtitle),
          schoolName: String(incoming.branding.schoolName ?? current.branding.schoolName),
          directorName: String(incoming.branding.directorName ?? current.branding.directorName),
          directorTitle: String(incoming.branding.directorTitle ?? current.branding.directorTitle),
          footerNote: String(incoming.branding.footerNote ?? current.branding.footerNote),
        }
      : current.branding;

    const next: ReportSettings = { gradeConfig, thresholds, branding };
    const { error } = await supabase
      .from('platform_settings')
      .upsert({ key: 'report', value: next, updated_at: new Date().toISOString(), updated_by: req.user?.id });

    if (error) throw error;

    await logAuditEvent({
      userId: req.user?.id,
      action: 'report_settings_updated',
      entityType: 'report_settings',
      entityId: 'report',
      ipAddress: clientIp(req),
    });

    res.json({ settings: next });
  } catch {
    res.status(500).json({ message: 'Failed to save report settings' });
  }
}

export async function getSettings(): Promise<ReportSettings> {
  const { data } = await supabase.from('platform_settings').select('value').eq('key', 'report').maybeSingle();
  return (data?.value as ReportSettings) || DEFAULT_SETTINGS;
}